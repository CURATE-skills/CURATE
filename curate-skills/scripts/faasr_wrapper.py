"""The FaaSr entry point for a plain step: a generated wrapper around its unchanged function.

A plain step (scripts/plain_contract.py) ships to FaaSr as two files, side by side:

  functions/<fn>_main.py   the step's function, byte-identical to the approved code
  functions/<fn>.py        this wrapper (render()), which FaaSr calls as <fn>(**Arguments)

FaaSr's FunctionGitRepo lists both (emit.py), so both land in the same folder. The wrapper
loads <fn>_main.py from its own folder and, per invocation:

  1. faasr_rank() if the step is ranked; fills {rank} into the file names
  2. faasr_get_file each input into a temp folder (a list: every copy; a folder input: every
     object faasr_get_folder_list returns under the input's prefix; an EMPTY folder input is
     an error, raised before main runs)
  3. main(inputs, outputs, params), with each non-blank stdout line forwarded to faasr_log
  4. checks every output exists, then faasr_put_file each one
  5. returns main's value (True/False drives a conditional InvokeNext)

The Arguments are the ones FaaSr always had (emit.faasr_arguments): folder, input1.., output1..
with {rank} left in, so workflow.json is unchanged. Standard library only.
"""
from __future__ import annotations

import ast
import hashlib

import plain_contract as PC

MAIN_SUFFIX = "_main"


def main_file(fn: str) -> str:
    return f"{fn}{MAIN_SUFFIX}.py"


def sha256(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def bundle_problems(spec) -> list[str]:
    """Why the steps of `spec` cannot be wrapped for FaaSr; empty if they can. Every step with
    code must be a plain function (a step without code is reported by write_bundle)."""
    problems = []
    names = {n.name for n in spec.nodes}
    plain = [n for n in spec.nodes if PC.is_plain(n.code)]
    for n in spec.nodes:
        if n.code and not PC.is_plain(n.code):
            problems.append(f"step {n.name} is not a plain main(inputs, outputs, params) function (the older "
                            "FaaSr style): regenerate it, or migrate the catalog it came from "
                            "(scripts/migrate_catalog.py)")
    for n in plain:
        clash = [m for m in names if f"{m}{MAIN_SUFFIX}" == n.name]
        if clash:
            problems.append(f"step {n.name}: its name is step {clash[0]}'s function file "
                            f"({main_file(clash[0])}); rename one of them")
        tree = ast.parse(n.code)
        top = {t.name for t in tree.body if isinstance(t, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))}
        top |= {x.id for t in tree.body if isinstance(t, (ast.Assign, ast.AnnAssign))
                for x in ast.walk(t) if isinstance(x, ast.Name) and isinstance(x.ctx, ast.Store)}
        top |= {(a.asname or a.name).split(".")[0] for t in tree.body if isinstance(t, (ast.Import, ast.ImportFrom))
                for a in t.names}
        if n.name in top:
            problems.append(f"step {n.name}: its function file defines a top-level {n.name!r}; FaaSr looks the "
                            f"step up by that name in every file, so rename it (the entry point is main)")
    if plain:
        layout, counted = PC.io_layout(spec)
        problems += counted
        problems += PC.folder_conflicts(spec, only={n.name for n in plain})
        for n in plain:
            for s in layout[n.name]["inputs"] + layout[n.name]["outputs"]:
                if s["kind"] == "list" and not s.get("copies"):
                    problems.append(f"step {n.name}: {s['slot']} ({s['file']}) has no known number of copies")
    return problems


TEMPLATE = '''\
# Generated by curate-skills: the FaaSr entry point for step {name}. Do not edit.
# The step's own function is {main_file}, unchanged (sha256 {sha}).
# FaaSr calls {name}(**Arguments); this wrapper downloads the inputs, calls
# main(inputs, outputs, params) on local paths, and uploads the outputs.
import contextlib
import importlib.util
import os
import sys
import tempfile
import traceback

_STEP = {name!r}
_MAIN_FILE = {main_file!r}
_MAIN_SHA256 = {sha!r}
_RANKED = {ranked!r}
_INPUTS = {inputs!r}  # (slot, kind, copies): kind one | list | folder
_OUTPUTS = {outputs!r}  # (slot, kind, copies): kind one | list


def {name}({signature}):
    return _curate_run(folder, {args})


def _curate_main():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), _MAIN_FILE)
    name = _MAIN_FILE[:-3]
    mod = sys.modules.get(name)
    if mod is None or os.path.abspath(getattr(mod, "__file__", "") or "") != path:
        spec = importlib.util.spec_from_file_location(name, path)
        mod = importlib.util.module_from_spec(spec)
        sys.modules[name] = mod
        spec.loader.exec_module(mod)
    return mod.main


class _ToFaaSrLog:
    """stdout during main(): each non-blank line goes to faasr_log (which refuses empty
    messages) and to the job's own stdout."""

    def __init__(self):
        self.buf = ""

    def write(self, text):
        sys.__stdout__.write(text)
        self.buf += text
        while "\\n" in self.buf:
            line, self.buf = self.buf.split("\\n", 1)
            self._send(line)
        return len(text)

    def flush(self):
        sys.__stdout__.flush()

    def close(self):
        self._send(self.buf)
        self.buf = ""

    @staticmethod
    def _send(line):
        if line.strip():
            faasr_log(line.rstrip())


def _name(name, rank):
    return name.replace("{{rank}}", str(rank)) if rank is not None else name


def _get(folder, remote, local):
    faasr_get_file(local_file=local, remote_folder=folder, remote_file=remote)
    if not os.path.exists(local):
        raise FileNotFoundError(f"{{_STEP}}: input {{folder}}/{{remote}} could not be downloaded")
    return local


def _curate_run(folder, args):
    rank = max_rank = None
    if _RANKED:
        r = faasr_rank()
        rank, max_rank = int(r["rank"]), int(r["max_rank"])
    work = tempfile.mkdtemp(prefix=f"curate_{{_STEP}}_")
    os.makedirs(os.path.join(work, "in"))
    os.makedirs(os.path.join(work, "out"))
    inputs = {{}}
    for slot, kind, copies in _INPUTS:
        name = args[slot]
        if kind == "one":
            n = _name(name, rank)
            inputs[slot] = _get(folder, n, os.path.join(work, "in", n))
        elif kind == "list":
            inputs[slot] = [_get(folder, _name(name, i), os.path.join(work, "in", _name(name, i)))
                            for i in range(1, copies + 1)]
        else:
            d = os.path.join(work, "dir_" + slot)
            os.makedirs(d)
            prefix = name.split("{{rank}}", 1)[0]
            got = 0
            for key in faasr_get_folder_list(prefix=f"{{folder}}/{{prefix}}" if folder else prefix):
                base = str(key).rstrip("/").rsplit("/", 1)[-1]
                if base.startswith(prefix) and not str(key).endswith("/"):
                    _get(folder, base, os.path.join(d, base))
                    got += 1
            if not got:  # a fan-in with nothing to read means the steps before it wrote nothing
                raise FileNotFoundError(f"{{_STEP}}: folder input {{slot}} ({{name}}) is empty: no file starting "
                                        f"with {{prefix!r}} in {{folder or 'the bucket'}}; the steps that write it "
                                        "produced nothing")
            inputs[slot] = d
    outputs, uploads = {{}}, []
    for slot, kind, copies in _OUTPUTS:
        names = [_name(args[slot], i) for i in range(1, copies + 1)] if kind == "list" else [_name(args[slot], rank)]
        paths = [os.path.join(work, "out", n) for n in names]
        uploads += zip(names, paths)
        outputs[slot] = paths if kind == "list" else paths[0]
    params = {{"rank": rank, "max_rank": max_rank}} if _RANKED else {{}}

    faasr_log(f"{{_STEP}}: main(inputs, outputs, params) from {{_MAIN_FILE}} (sha256 {{_MAIN_SHA256[:12]}})"
              + (f", rank {{rank}}/{{max_rank}}" if _RANKED else ""))
    log = _ToFaaSrLog()
    try:
        with contextlib.redirect_stdout(log):
            result = _curate_main()(inputs, outputs, params)
    except BaseException:
        log.close()
        faasr_log(f"{{_STEP}}: main raised:\\n" + traceback.format_exc())
        raise
    log.close()

    missing = [n for n, p in uploads if not os.path.exists(p)]
    if missing:
        raise RuntimeError(f"{{_STEP}}: main did not write its declared output(s) {{missing}}")
    for n, p in uploads:
        faasr_put_file(local_file=p, remote_folder=folder, remote_file=n)
    faasr_log(f"{{_STEP}}: uploaded {{len(uploads)}} output(s)")
    return result
'''


def render(spec, node) -> str:
    """The wrapper file for one plain step of `spec`."""
    layout, _ = PC.io_layout(spec)
    lay = layout[node.name]
    slots = [f"input{i}" for i in range(1, len(node.inputs) + 1)] + \
            [f"output{i}" for i in range(1, len(node.outputs) + 1)]
    return TEMPLATE.format(
        name=node.name, main_file=main_file(node.name), sha=sha256(node.code),
        ranked=lay["rank"] > 1,
        inputs=[(s["slot"], s["kind"], s.get("copies")) for s in lay["inputs"]],
        outputs=[(s["slot"], s["kind"], s.get("copies")) for s in lay["outputs"]],
        signature=", ".join(["folder"] + slots),
        args="{" + ", ".join(f"{s!r}: {s}" for s in slots) + "}")
